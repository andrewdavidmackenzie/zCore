//! Minimal framebuffer text console for kernel log output.
//!
//! Uses an 8x16 bitmap font to render text directly to the bootloader-provided
//! framebuffer. Kernel-only -- not exposed to userspace.

use lock::Mutex;

/// Character cell size in pixels.
const CHAR_W: u32 = 8;
const CHAR_H: u32 = 16;

/// Framebuffer console state.
struct FbConsole {
    /// Virtual address of the framebuffer.
    base: *mut u32,
    /// Width in pixels.
    width: u32,
    /// Height in pixels.
    height: u32,
    /// Stride in pixels (may differ from width).
    stride: u32,
    /// Current cursor position (column, row) in character cells.
    col: u32,
    row: u32,
    /// Maximum columns and rows.
    max_col: u32,
    max_row: u32,
}

unsafe impl Send for FbConsole {}

static FB_CONSOLE: Mutex<Option<FbConsole>> = Mutex::new(None);

/// Initialize the framebuffer console from the kernel config.
/// Must be called after the framebuffer virtual mapping is available.
pub fn init() {
    let fb = match crate::KCONFIG.framebuffer {
        Some(ref fb) => fb,
        None => return,
    };

    // The bootloader maps the framebuffer at a fixed virtual address.
    // Convert physical address to virtual using the phys_to_virt offset.
    let vaddr = (fb.addr as usize) + crate::KCONFIG.phys_to_virt_offset;

    let console = FbConsole {
        base: vaddr as *mut u32,
        width: fb.width,
        height: fb.height,
        stride: fb.stride,
        col: 0,
        row: 0,
        max_col: fb.width / CHAR_W,
        max_row: fb.height / CHAR_H,
    };

    // Clear screen to dark blue (visible sign of life).
    let bg = 0x00102040u32; // dark blue-grey
    unsafe {
        for y in 0..console.height {
            for x in 0..console.width {
                let offset = (y * console.stride + x) as isize;
                core::ptr::write_volatile(console.base.offset(offset), bg);
            }
        }
    }

    *FB_CONSOLE.lock() = Some(console);
}

/// Write a string to the framebuffer console.
pub fn write_str(s: &str) {
    let mut console = FB_CONSOLE.lock();
    let console = match console.as_mut() {
        Some(c) => c,
        None => return,
    };

    for byte in s.bytes() {
        match byte {
            b'\n' | b'\r' => {
                if byte == b'\n' {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            b'\t' => {
                console.col = (console.col + 4) & !3;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            0x20..=0x7e => {
                draw_char(console, byte, console.col, console.row);
                console.col += 1;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            // Skip ANSI escape sequences (color codes from the logger).
            0x1b => {} // Start of escape -- handled by skipping until 'm'
            _ => {}    // Ignore other control chars
        }
    }
}

fn scroll_up(console: &mut FbConsole) {
    let row_bytes = console.stride as usize;
    let char_rows = CHAR_H as usize;
    unsafe {
        // Move all rows up by one character row.
        for y in 0..(console.height as usize - char_rows) {
            let dst = console.base.add(y * row_bytes);
            let src = console.base.add((y + char_rows) * row_bytes);
            core::ptr::copy(src, dst, row_bytes);
        }
        // Clear the bottom row.
        let bg = 0x00102040u32;
        for y in (console.height as usize - char_rows)..console.height as usize {
            for x in 0..console.width as usize {
                core::ptr::write_volatile(console.base.add(y * row_bytes + x), bg);
            }
        }
    }
    console.row = console.max_row - 1;
}

fn draw_char(console: &FbConsole, ch: u8, col: u32, row: u32) {
    let fg = 0x00C0C0C0u32; // light grey
    let bg = 0x00102040u32; // dark blue-grey
    let glyph = &FONT_8X16[(ch as usize) * 16..(ch as usize) * 16 + 16];

    let x0 = col * CHAR_W;
    let y0 = row * CHAR_H;

    for (dy, &glyph_row) in glyph.iter().enumerate() {
        for dx in 0..8u32 {
            let pixel = if (glyph_row >> (7 - dx)) & 1 != 0 {
                fg
            } else {
                bg
            };
            let offset = ((y0 + dy as u32) * console.stride + x0 + dx) as isize;
            unsafe {
                core::ptr::write_volatile(console.base.offset(offset), pixel);
            }
        }
    }
}

