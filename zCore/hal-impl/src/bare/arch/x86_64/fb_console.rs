//! Minimal framebuffer text console for kernel log output.
//!
//! Uses an 8x16 bitmap font to render text directly to the bootloader-provided
//! framebuffer. Kernel-only -- not exposed to userspace.

use lock::Mutex;

/// Character cell size in pixels.
const CHAR_W: u32 = 8;
const CHAR_H: u32 = 16;

/// Framebuffer console state.
struct FbConsole {
    /// Virtual address of the framebuffer.
    base: *mut u8,
    /// Width in pixels.
    width: u32,
    /// Height in pixels.
    height: u32,
    /// Stride in bytes (stride_pixels * bpp).
    stride_bytes: u32,
    /// Bytes per pixel (3 for BGR, 4 for BGRA).
    bpp: u32,
    /// Current cursor position (column, row) in character cells.
    col: u32,
    row: u32,
    /// Maximum columns and rows.
    max_col: u32,
    max_row: u32,
    /// True when inside an ANSI escape sequence (suppress output).
    in_escape: bool,
}

unsafe impl Send for FbConsole {}

static FB_CONSOLE: Mutex<Option<FbConsole>> = Mutex::new(None);

/// Initialize the framebuffer console from the kernel config.
/// Must be called after the framebuffer virtual mapping is available.
pub fn init() {
    let fb = match *super::config::FRAMEBUFFER {
        Some(ref fb) => fb,
        None => return,
    };

    // The bootloader maps the framebuffer at a fixed virtual address.
    // Convert physical address to virtual using the phys_to_virt offset.
    let vaddr = (fb.addr as usize) + crate::KCONFIG.phys_to_virt_offset;

    // Bytes per pixel: typically 3 (BGR) or 4 (BGRA).
    // Default to 4 if not specified (FramebufferInfo doesn't have bpp,
    // so infer from size: size / (height * stride) = bpp).
    let bpp = if fb.height > 0 && fb.stride > 0 {
        let total_pixels = fb.height as u64 * fb.stride as u64;
        (fb.size.checked_div(total_pixels).unwrap_or(4)) as u32
    } else {
        4
    };

    let console = FbConsole {
        base: vaddr as *mut u8,
        width: fb.width,
        height: fb.height,
        stride_bytes: fb.stride * bpp,
        bpp,
        col: 0,
        row: 0,
        max_col: fb.width / CHAR_W,
        max_row: fb.height / CHAR_H,
        in_escape: false,
    };

    // Clear screen to dark blue (visible sign of life).
    // Use a bulk memset approach: fill each scanline with the background
    // pixel repeated. For uniform colors where B==G==R, we could use
    // write_bytes, but our dark blue background (B=0x40,G=0x20,R=0x10)
    // has distinct channel values. Build one scanline, then replicate.
    unsafe {
        let stride = console.stride_bytes as usize;
        let w = console.width as usize;
        // Build a single scanline buffer with the background pattern.
        let scanline = alloc::vec![0u8; stride];
        // Fill it with background pixels (alloc inits to zero, so alpha is 0x00).
        let scanline = {
            let mut s = scanline;
            for x in 0..w {
                let off = x * bpp as usize;
                s[off] = 0x40; // B
                if bpp >= 2 {
                    s[off + 1] = 0x20; // G
                }
                if bpp >= 3 {
                    s[off + 2] = 0x10; // R
                }
            }
            s
        };
        // Blast the scanline to every row.
        for y in 0..console.height as usize {
            core::ptr::copy_nonoverlapping(scanline.as_ptr(), console.base.add(y * stride), stride);
        }
    }

    *FB_CONSOLE.lock() = Some(console);
}

/// Write a string to the framebuffer console.
pub fn write_str(s: &str) {
    let mut console = FB_CONSOLE.lock();
    let console = match console.as_mut() {
        Some(c) => c,
        None => return,
    };

    for byte in s.bytes() {
        // Suppress ANSI escape sequences (e.g. "\x1b[31m" color codes).
        // Format: ESC [ <parameter bytes 0x30-0x3F>* <final byte 0x40-0x7E>
        // The '[' (0x5B) is the CSI introducer, not a final byte.
        if console.in_escape {
            // Final bytes are 0x40..=0x7E, but skip '[' (0x5B) which is
            // the CSI introducer, and intermediate bytes (0x20..=0x2F).
            if matches!(byte, 0x40..=0x7E) && byte != b'[' {
                console.in_escape = false;
            }
            continue;
        }

        match byte {
            0x1b => {
                console.in_escape = true;
            }
            b'\n' | b'\r' => {
                if byte == b'\n' {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            b'\t' => {
                console.col = (console.col + 4) & !3;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            0x20..=0x7e => {
                draw_char(console, byte, console.col, console.row);
                console.col += 1;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            _ => {} // Ignore other control chars
        }
    }
}

fn scroll_up(console: &mut FbConsole) {
    let stride = console.stride_bytes as usize;
    let char_rows = CHAR_H as usize;
    let bpp = console.bpp as usize;
    let scroll_lines = console.height as usize - char_rows;
    unsafe {
        // Move all rows up by one character row in a single bulk copy.
        let dst = console.base;
        let src = console.base.add(char_rows * stride);
        core::ptr::copy(src, dst, scroll_lines * stride);
        // Clear the bottom character row using a scanline pattern.
        let w = console.width as usize;
        let mut bg_line = alloc::vec![0u8; stride];
        for x in 0..w {
            let off = x * bpp;
            bg_line[off] = 0x40;
            if bpp >= 2 {
                bg_line[off + 1] = 0x20;
            }
            if bpp >= 3 {
                bg_line[off + 2] = 0x10;
            }
        }
        for y in scroll_lines..console.height as usize {
            core::ptr::copy_nonoverlapping(bg_line.as_ptr(), console.base.add(y * stride), stride);
        }
    }
    console.row = console.max_row - 1;
}

fn draw_char(console: &FbConsole, ch: u8, col: u32, row: u32) {
    let glyph = &FONT_8X16[(ch as usize) * 16..(ch as usize) * 16 + 16];
    let bpp = console.bpp as usize;
    let stride = console.stride_bytes as usize;
    let x0 = (col * CHAR_W) as usize;
    let y0 = (row * CHAR_H) as usize;
    let char_stride = CHAR_W as usize * bpp;

    // Foreground: light grey (BGR: B=0xC0, G=0xC0, R=0xC0)
    // Background: dark blue-grey (BGR: B=0x40, G=0x20, R=0x10)
    // Build each glyph scanline into a buffer, then copy it out in one
    // operation. This reduces framebuffer writes from 8*bpp volatile
    // stores per row to a single copy_nonoverlapping per row.
    let mut buf = [0u8; 8 * 4]; // max 8 pixels * 4 bpp
    for (dy, &glyph_row) in glyph.iter().enumerate() {
        for dx in 0..8usize {
            let is_fg = (glyph_row >> (7 - dx)) & 1 != 0;
            let off = dx * bpp;
            if is_fg {
                buf[off] = 0xC0;
                if bpp >= 2 {
                    buf[off + 1] = 0xC0;
                }
                if bpp >= 3 {
                    buf[off + 2] = 0xC0;
                }
                if bpp >= 4 {
                    buf[off + 3] = 0xFF;
                }
            } else {
                buf[off] = 0x40;
                if bpp >= 2 {
                    buf[off + 1] = 0x20;
                }
                if bpp >= 3 {
                    buf[off + 2] = 0x10;
                }
                if bpp >= 4 {
                    buf[off + 3] = 0x00;
                }
            }
        }
        unsafe {
            core::ptr::copy_nonoverlapping(
                buf.as_ptr(),
                console.base.add((y0 + dy) * stride + x0 * bpp),
                char_stride,
            );
        }
    }
}

