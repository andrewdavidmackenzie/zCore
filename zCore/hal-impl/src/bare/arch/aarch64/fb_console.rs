//! Minimal framebuffer text console for Jolla C2 kernel log output.
//!
//! Renders 8x16 bitmap font directly to the display controller's
//! framebuffer. No allocator needed -- uses the x86_64 fb_console's
//! font data but avoids alloc for scroll/clear (writes pixel-by-pixel).
//!
//! Framebuffer: 720x1600 ARGB8888 at physical 0x9e000000.
//! The identity mapping (TTBR0) keeps this accessible from EL1.

use lock::Mutex;

const CHAR_W: u32 = 8;
const CHAR_H: u32 = 16;

// Jolla C2 framebuffer parameters (from hw-reference.md)
const FB_PHYS: usize = 0x9e00_0000;
const FB_WIDTH: u32 = 720;
const FB_HEIGHT: u32 = 1600;
const FB_BPP: u32 = 4; // ARGB8888
const FB_STRIDE_BYTES: u32 = FB_WIDTH * FB_BPP;

struct FbConsole {
    base: *mut u8,
    col: u32,
    row: u32,
    max_col: u32,
    max_row: u32,
    in_escape: bool,
}

unsafe impl Send for FbConsole {}

static FB_CONSOLE: Mutex<Option<FbConsole>> = Mutex::new(None);

/// Initialize the framebuffer console.
/// Can be called very early (before KCONFIG is set). Uses the
/// identity-mapped physical address directly (TTBR0 still active).
pub fn init() {
    // Use the physical address directly via the identity map (TTBR0).
    // The high virtual mapping (TTBR1) maps 0x80-0xBF as normal memory
    // with caches, which doesn't work for device MMIO like the framebuffer.
    let base = FB_PHYS as *mut u8;

    let console = FbConsole {
        base,
        col: 0,
        row: 0,
        max_col: FB_WIDTH / CHAR_W,
        max_row: FB_HEIGHT / CHAR_H,
        in_escape: false,
    };

    // Clear screen to solid black so it's obvious we reached rust_main.
    // This overwrites the debug bars, but that's OK — we know boot works.
    unsafe {
        let total_pixels = (FB_WIDTH * FB_HEIGHT) as usize;
        let ptr = base as *mut u32;
        for i in 0..total_pixels {
            core::ptr::write_volatile(ptr.add(i), 0xFF000000); // opaque black
        }
        // Flush entire framebuffer from cache.
        #[cfg(target_arch = "aarch64")]
        {
            let fb_size = total_pixels * 4;
            let mut addr = base as usize;
            while addr < base as usize + fb_size {
                core::arch::asm!(
                    "dc cvac, {addr}",
                    addr = in(reg) addr,
                    options(nostack, preserves_flags),
                );
                addr += 64; // cache line size
            }
            core::arch::asm!("dsb sy", options(nostack, preserves_flags));
        }
    }

    *FB_CONSOLE.lock() = Some(console);
}

/// Switch the framebuffer console from the identity-mapped physical address
/// (via TTBR0) to the high virtual address (via TTBR1). Must be called
/// after the kernel page table maps the FB region as device memory and
/// before TTBR0 is zeroed.
pub fn remap() {
    let mut guard = FB_CONSOLE.lock();
    if let Some(console) = guard.as_mut() {
        let virt_base = crate::mem::phys_to_virt(FB_PHYS) as *mut u8;
        console.base = virt_base;
    }
}

/// Write a string to the framebuffer console.
pub fn write_str(s: &str) {
    let mut guard = FB_CONSOLE.lock();
    let console = match guard.as_mut() {
        Some(c) => c,
        None => return,
    };

    for byte in s.bytes() {
        if console.in_escape {
            if matches!(byte, 0x40..=0x7E) && byte != b'[' {
                console.in_escape = false;
            }
            continue;
        }

        match byte {
            0x1b => {
                console.in_escape = true;
            }
            b'\n' | b'\r' => {
                if byte == b'\n' {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            b'\t' => {
                console.col = (console.col + 4) & !3;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            0x20..=0x7e => {
                draw_char(console, byte, console.col, console.row);
                console.col += 1;
                if console.col >= console.max_col {
                    console.col = 0;
                    console.row += 1;
                    if console.row >= console.max_row {
                        scroll_up(console);
                    }
                }
            }
            _ => {}
        }
    }
}

fn scroll_up(console: &mut FbConsole) {
    let stride = FB_STRIDE_BYTES as usize;
    let char_rows = CHAR_H as usize;
    let scroll_lines = FB_HEIGHT as usize - char_rows;
    unsafe {
        let dst = console.base;
        let src = console.base.add(char_rows * stride);
        core::ptr::copy(src, dst, scroll_lines * stride);
        // Clear bottom row with black pixel-by-pixel.
        for y in scroll_lines..FB_HEIGHT as usize {
            for x in 0..FB_WIDTH as usize {
                let off = y * stride + x * FB_BPP as usize;
                core::ptr::write_volatile(console.base.add(off) as *mut u32, 0xFF000000);
            }
        }
        // Flush entire framebuffer from cache after scroll + clear.
        #[cfg(target_arch = "aarch64")]
        {
            let fb_size = (FB_WIDTH * FB_HEIGHT * FB_BPP) as usize;
            let mut addr = console.base as usize;
            let end = addr + fb_size;
            while addr < end {
                core::arch::asm!(
                    "dc cvac, {addr}",
                    addr = in(reg) addr,
                    options(nostack, preserves_flags),
                );
                addr += 64;
            }
            core::arch::asm!("dsb sy", options(nostack, preserves_flags));
        }
    }
    console.row = console.max_row - 1;
}

fn draw_char(console: &FbConsole, ch: u8, col: u32, row: u32) {
    if (ch as usize) >= 128 {
        return;
    }
    let glyph = &FONT_8X16[(ch as usize) * 16..(ch as usize) * 16 + 16];
    let stride = FB_STRIDE_BYTES as usize;
    let x0 = (col * CHAR_W) as usize;
    let y0 = (row * CHAR_H) as usize;

    // ARGB8888: foreground = white (0xFFFFFFFF), background = black (0xFF000000)
    for (dy, &glyph_row) in glyph.iter().enumerate() {
        for dx in 0..8usize {
            let is_fg = (glyph_row >> (7 - dx)) & 1 != 0;
            let pixel: u32 = if is_fg { 0xFFFF_FFFF } else { 0xFF00_0000 };
            let off = (y0 + dy) * stride + (x0 + dx) * FB_BPP as usize;
            unsafe {
                let addr = console.base.add(off);
                core::ptr::write_volatile(addr as *mut u32, pixel);
                // Flush cache line to ensure pixel reaches the display controller.
                // The FB is mapped as normal memory, so writes are cached.
                #[cfg(target_arch = "aarch64")]
                core::arch::asm!(
                    "dc cvac, {addr}",
                    addr = in(reg) addr,
                    options(nostack, preserves_flags),
                );
            }
        }
        // Data synchronization barrier after each scanline.
        #[cfg(target_arch = "aarch64")]
        unsafe {
            core::arch::asm!("dsb sy", options(nostack, preserves_flags));
        }
    }
}

